function geometry(icon) {
  return icon.svg
    .match(/^<svg\b[^>]*>\s*([\s\S]*?)\s*<\/svg>$/)[1]
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
}

function indent(lines, spaces) {
  const prefix = ' '.repeat(spaces)
  return lines.map((line) => `${prefix}${line}`).join('\n')
}

function jsxGeometry(lines) {
  return lines.map((line) =>
    line
      .replaceAll('stroke-width=', 'strokeWidth=')
      .replaceAll('stroke-linecap=', 'strokeLinecap=')
      .replaceAll('stroke-linejoin=', 'strokeLinejoin=')
      .replaceAll('fill-rule=', 'fillRule=')
      .replaceAll('clip-rule=', 'clipRule=')
  )
}

function wrapGeometry(lines, wrapSingleAttribute = true) {
  return lines.flatMap((line) => {
    if (line.length <= 76) return line

    const match = line.match(/^<(\w+)\s+(.+)\s\/>$/)
    if (!match) return line

    const attributes = [...match[2].matchAll(/([\w:-]+)="([^"]*)"/g)].map(
      ([, name, value]) => `${name}="${value}"`
    )

    if (!wrapSingleAttribute && attributes.length === 1) return line

    return [
      `<${match[1]}`,
      ...attributes.map((attribute) => `  ${attribute}`),
      '/>'
    ]
  })
}

export function iconSource(icon, framework) {
  const lines = geometry(icon)

  if (framework === 'react') {
    return `import { forwardRef } from "react";

const ${icon.name} = forwardRef(function ${icon.name}(props, ref) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox="0 0 24 24"
      width="1em"
      height="1em"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      data-slot="icon"
      {...props}
      ref={ref}
    >
${indent(wrapGeometry(jsxGeometry(lines), false), 6)}
    </svg>
  );
});

export default ${icon.name};
`
  }

  if (framework === 'svelte') {
    return `<script>
  let { ...props } = $props();
</script>

<svg
  xmlns="http://www.w3.org/2000/svg"
  viewBox="0 0 24 24"
  width="1em"
  height="1em"
  fill="none"
  stroke="currentColor"
  stroke-width="1.5"
  stroke-linecap="round"
  stroke-linejoin="round"
  aria-hidden="true"
  focusable="false"
  data-slot="icon"
  {...props}
>
${indent(wrapGeometry(lines), 2)}
</svg>
`
  }

  return `<script setup>
defineOptions({ inheritAttrs: false });
</script>

<template>
  <svg
    xmlns="http://www.w3.org/2000/svg"
    viewBox="0 0 24 24"
    width="1em"
    height="1em"
    fill="none"
    stroke="currentColor"
    stroke-width="1.5"
    stroke-linecap="round"
    stroke-linejoin="round"
    aria-hidden="true"
    focusable="false"
    data-slot="icon"
    v-bind="$attrs"
  >
${indent(wrapGeometry(lines), 4)}
  </svg>
</template>
`
}
